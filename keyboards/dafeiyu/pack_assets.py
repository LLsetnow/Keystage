"""Encode the source PNGs as lossless WebP with cwebp and embed them for offline use."""

from base64 import b64encode
import json
from pathlib import Path
import subprocess


HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parent.parent / "js/dafeiyu_assets.js"


def build_manifest():
    config = json.loads((HERE / "keycap_config.json").read_text(encoding="utf-8"))
    manifest = {}
    for key in config["keys"]:
        path = HERE / key["image"]
        webp = subprocess.run(
            ["cwebp", "-quiet", "-lossless", "-z", "6", "-exact", "-metadata", "icc", str(path), "-o", "-"],
            check=True,
            capture_output=True,
        ).stdout
        manifest[key["code"]] = {
            "url": "data:image/webp;base64," + b64encode(webp).decode("ascii"),
            "bg": key["bgColor"],
            "source": path.name,
        }

    sources = {entry["source"] for entry in manifest.values()}
    files = {path.name for path in (HERE / "complete").glob("*.png")}
    if len(config["keys"]) != 104 or len(manifest) != 104 or len(sources) != 104 or sources != files:
        raise ValueError("Expected exactly one PNG for each of the 104 key codes")
    return manifest


if __name__ == "__main__":
    data = json.dumps(build_manifest(), indent=2)
    OUTPUT.write_text(
        "// Generated by keyboards/dafeiyu/pack_assets.py\n"
        f"(function (KB) {{\n  KB.DAFEIYU_ASSETS = {data};\n}})(window.KB);\n",
        encoding="utf-8",
    )
